/* USER CODE BEGIN 4 */
void Task_ADC(void)
{
    t1_in = HAL_GetTick();
    HAL_ADC_Start(&hadc1);
    if (HAL_ADC_PollForConversion(&hadc1, 100) == HAL_OK)
    {
        adc_val = HAL_ADC_GetValue(&hadc1);
    }
    HAL_ADC_Stop(&hadc1);
	float tu_so = (float)adc_val - (float)ADC_DRY;
	float mau_so = (float)ADC_WET - (float)ADC_DRY;
	hum = (tu_so / mau_so) * 100.0f;
	if (hum > 100.0f) hum = 100.0f;
	if (hum < 0.0f) hum = 0.0f;
    t1_out = HAL_GetTick();
}

void Task_DHT(void)
{
    t2_in = HAL_GetTick();
    if (DHT22_Read(&dht, &dht_data) == 0)
    {
        temp = dht_data.Temperature;
        // hum = dht_data.Humidity;
    }
    t2_out = HAL_GetTick();
}

void Task_LCD(void)
{
    t3_in = HAL_GetTick();


    sprintf(str_buff, "Temp: %.1fC   ", temp);
    lcd_put_cur(0, 0);
    lcd_send_string(str_buff);

    sprintf(str_buff, "Soil: %.1f%%   ", hum);
    lcd_put_cur(1, 0);
    lcd_send_string(str_buff);

    t3_out = HAL_GetTick();
}

void Task_UART(void)
{
    t4_in = HAL_GetTick();

    sprintf(str_buff, "Temp: %.1f Soil: %.1f%%\r\n", temp, hum);
    HAL_UART_Transmit(&huart1, (uint8_t*)str_buff, strlen(str_buff), 100);

    t4_out = HAL_GetTick();
}

